def _example(user: str, assistant: str) -> dict[str, object]:
    return {
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant},
        ]
    }


def _conversation(messages: list[tuple[str, str]]) -> dict[str, object]:
    return {
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            *[{"role": role, "content": content} for role, content in messages],
        ]
    }


def build_examples() -> list[dict[str, object]]:
    examples: list[dict[str, object]] = []
    safety_examples = SAFETY + SAFETY_PRESSURE
    basic_examples = COMMANDS + TOOL_TASKS + safety_examples + MEMORY + EQ
    basic_examples += IDENTITY + GENERAL
    for user, assistant in basic_examples:
        examples.append(_example(user, assistant))
    for user, assistant in safety_examples:
        for prefix in ("请", "帮我", "现在", "立刻"):
            examples.append(_example(f"{prefix}{user}", assistant))
        # Safety behavior is more important than style variety; repeat these
        # examples so a small local model cannot ignore the boundary.
        for _ in range(6):
            examples.append(_example(user, assistant))
    for user, assistant in EQ:
        for _ in range(5):
            examples.append(_example(user, assistant))
    for user, assistant in COMMANDS:
        for prefix in ("贾维斯，", "Jarvis，", "麻烦你", "帮我"):
            examples.append(_example(f"{prefix}{user}", assistant))
    for user, assistant in EQ + IDENTITY + GENERAL:
        for prefix in ("贾维斯，", "Jarvis，", "麻烦你"):
            examples.append(_example(f"{prefix}{user}", assistant))
    for messages in CONVERSATIONS:
        examples.append(_conversation(messages))
    random.Random(42).shuffle(examples)
    return examples


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    examples = build_examples()
    output = DATA_DIR / "jarvis_sft.jsonl"
    with output.open("w", encoding="utf-8") as handle:
        for item in examples:
            handle.write(json.dumps(item, ensure_ascii=False) + "\n")
    print(f"wrote {len(examples)} examples to {output}")


if __name__ == "__main__":
    main()
